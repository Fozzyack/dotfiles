for severity, color in pairs({ Error = p.bright_red, Warn = p.bright_yellow, Info = p.bright_blue, Hint = p.teal }) do
    groups["Diagnostic" .. severity] = { fg = color }
    groups["DiagnosticSign" .. severity] = { fg = color }
    groups["DiagnosticFloating" .. severity] = { fg = color, bg = p.mantle }
    groups["DiagnosticVirtualText" .. severity] = { fg = color, bg = p.line }
    groups["DiagnosticUnderline" .. severity] = { sp = color, undercurl = true }
end

for level, color in ipairs({ p.accent, p.teal, p.bright_yellow, p.bright_blue, p.magenta, p.green }) do
    groups["RenderMarkdownH" .. level] = { fg = color, bold = true }
    groups["RenderMarkdownH" .. level .. "Bg"] = { bg = p.line }
end

for name, opts in pairs(groups) do
    vim.api.nvim_set_hl(0, name, opts)
end

-- Keep Neovim's embedded terminal identical to WezTerm's ANSI palette.
